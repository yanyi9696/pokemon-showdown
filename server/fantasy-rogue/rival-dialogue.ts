export function rivalChapterReplay(id: RivalID, chapter: number) {
	type Page = { text: string[], options: { label: string, next: string }[], portrait?: string, battleSkipped?: boolean };
	const pages: Record<string, Page> = {};
	const opening = rivalOpeningPages(id, chapter, 0);
	for (const [index, page] of opening.entries()) pages[`intro${index}`] = { text: [page.text], portrait: page.portrait,
		options: index + 1 < opening.length ? [{ label: '继续对话', next: `intro${index + 1}` }] :
		rivalConversationOptions(chapter).map(option => ({ label: option.name, next: `answer0:${option.id}` })) };
	for (const turn of [0, 1]) for (const option of rivalConversationOptions(chapter, turn)) {
		const key = `answer${turn}:${option.id}`;
		pages[key] = { text: rivalAnswerPages(id, chapter, turn, option.id, 4).map(page => page.text), portrait: id,
			options: turn === 0 ? rivalConversationOptions(chapter, 1).map(next => ({ label: next.name, next: `answer1:${next.id}` })) :
			[{ label: chapter === 4 ? '继续旅途闲谈' : chapter === 5 ? '合作完成委托' : '继续这段奇遇', next: 'activity' }] };
	}
	pages.activity = { text: [RIVALS[id].lines[chapter - 1], VOICES[id].chapters[chapter - 1]], portrait: id,
		options: [{ label: '查看后续', next: 'end' }], battleSkipped: ![4, 5].includes(chapter) };
	if (chapter === 4) {
		const options = (turn: number) => rivalChatOptions(turn).map(option => ({ label: option.name, next: `chat${turn}:${option.id}` }));
		pages.activity.options = options(0);
		for (const turn of [0, 1, 2]) for (const option of rivalChatOptions(turn)) {
			pages[`chat${turn}:${option.id}`] = { text: rivalChatPages(id, turn, option.id, 4).map(page => page.text), portrait: id,
				options: turn < 2 ? options(turn + 1) : [{ label: '收好心意，继续旅程', next: 'end' }] };
		}
	}
	pages.end = { text: [chapter === 1 ? '切磋之后，你们确立了劲敌的约定。以后遇见，记得多来走走，一起经历更多事情。' :
		chapter === 8 ? '这场全力对决结束了。无论胜负，对方都真心认可了你，并发出永久同行的邀请。' :
		'你们收好旅途的收获，约定下次见面再交换新的故事。回应与相处，会让彼此逐渐熟悉。'], portrait: id, options: [] };
	return { title: `与${RIVALS[id].name}的相遇·其${'一二三四五六七八'[chapter - 1]}`, start: 'intro0', pages };
}
