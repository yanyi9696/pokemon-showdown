/** Choice IDs remain stable for saved conversations; cold now means composed, never rude. */
export const RIVAL_STYLES: Record<RivalID | 'carmine', readonly string[]> = {
	kieran: ['honest', 'warm', 'cold'], penny: ['cold', 'honest', 'warm'],
	marnie: ['honest', 'cold', 'warm'], lana: ['cold', 'honest', 'warm'],
	lillie: ['honest', 'warm', 'cold'], korrina: ['warm', 'honest', 'cold'],
	nemona: ['warm', 'cold', 'honest'], blue: ['cold', 'warm', 'honest'],
	gladion: ['cold', 'honest', 'warm'], bede: ['cold', 'warm', 'honest'],
	n: ['honest', 'cold', 'warm'], silver: ['cold', 'honest', 'warm'],
	carmine: ['warm', 'cold', 'honest'],
};
export function rivalAffectionGain(id: RivalID | 'carmine', choice: string, chapter: number) {
	const style = choice.replace('greet:', '');
	const rank = RIVAL_STYLES[id].indexOf(style);
	if (rank < 0) return 0;
	return chapter <= 2 ? rank === 0 ? 2 : 1 : 3 - rank;
}

